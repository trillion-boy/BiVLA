#!/usr/bin/env python3
"""The two focused ablation tables for Results (Section IV-B), the ones whose
runs are controls and so never appear in the main grid:

  tablekeep.tex    Result 2. Foveation keep sweep on OpenVLA/Bridge. The gain
                   grows as LESS is discarded and peaks where nothing is, which
                   is the evidence that foveation helps as an input transform,
                   not by spending less. Compute barely moves across the sweep.

  tablewindow.tex  Result 1. Depth pruning, four layers removed in every row,
                   only the eligibility window changed. The paired change swings
                   from a gain to a large loss inside one cell, and the span of
                   that swing is itself a property of the cell.

Both are computed here from the episode records, McNemar exact, so they cannot
drift from verify_all.py. The cell/path definitions are spelled out because
these are controls with irregular directory names, exactly as verify_all does.

The comprehensive paired-change grid (every condition, with significance) is a
third ablation, generated by make_grid_table.py -> tablechanges.tex.
"""
import glob
import json
import os
from math import comb

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(HERE, "paper")


def load(pat):
    out = {}
    for f in glob.glob(os.path.join(ROOT, pat), recursive=True):
        s = json.load(open(f))
        for e in s["episodes"]:
            out[(s["task"], int(e["ep_id"]))] = bool(e["success"])
    return out


def lat(pat):
    """Episode-weighted model time per call, ms, or None."""
    vals = []
    for f in glob.glob(os.path.join(ROOT, pat), recursive=True):
        s = json.load(open(f))
        run = s.get("avg_model_ms_per_infer")
        if run is None:
            run = (s.get("model_stats") or {}).get("model_ms_per_infer")
        for e in s["episodes"]:
            v = (e.get("model_ms_per_infer")
                 or (e.get("model_stats") or {}).get("model_ms_per_infer") or run)
            if v is not None:
                vals.append(v)
    return sum(vals) / len(vals) if vals else None


def mcn(a, b):
    k = sorted(set(a) & set(b))
    n = len(k)
    br = sum(a[i] and not b[i] for i in k)
    fx = sum(b[i] and not a[i] for i in k)
    m = br + fx
    p = 1.0 if m == 0 else min(1.0, 2 * sum(comb(m, x)
                               for x in range(min(br, fx) + 1)) / 2 ** m)
    d = 100.0 * (sum(b[i] for i in k) - sum(a[i] for i in k)) / n
    return n, d, p


def pfmt(p):
    if p < 1e-3:
        return "$%.0f{\\times}10^{%d}$" % _sci(p)
    return "$%.2g$" % p if p < 0.1 else "$%.2f$" % p


def _sci(p):
    import math
    e = math.floor(math.log10(p))
    return p / 10 ** e, e


def dfmt(d):
    return "$%+.1f$" % d


BRIDGE_BASE = "results/openvla_bridge_0805/baseline/**/results_*.json"


def keep_table():
    base = load(BRIDGE_BASE)
    b_lat = lat(BRIDGE_BASE)
    # keep 20% is the grid cell, imported from RetinaBased; the rest are the
    # openvla_bridge_foveate_sweep controls. Ordered most-discarded first so
    # the column reads as a capacity axis.
    rows = [
        ("10", "results/openvla_bridge_foveate_sweep/keep10/**/results_*.json"),
        ("20", "RetinaBased/GoogleColab/results_reproduction_eager/"
               "openvla_foveated/**/results_*.json"),
        ("40", "results/openvla_bridge_foveate_sweep/keep40/**/results_*.json"),
        ("100", "results/openvla_bridge_foveate_sweep/keep100/**/results_*.json"),
    ]
    body = []
    for keep, pat in rows:
        n, d, p = mcn(base, load(pat))
        cl = lat(pat)
        comp = ("$%+.1f$" % (100.0 * (cl - b_lat) / b_lat)
                if cl and b_lat else r"\textemdash")
        body.append(f"${keep}$ & {dfmt(d)} & {pfmt(p)} & {comp} \\\\")
    tex = r"""%% Generated by make_ablation_tables.py. Result 2: foveation keep sweep,
%% OpenVLA/Bridge, 96 episodes each, paired against the same baseline.
%% "Keep" is the fraction of the observation retained; 100 discards nothing and
%% only the log-polar round trip remains. Do not edit; regenerate.
\begin{table}[t]
\centering
\caption{Foveation on OpenVLA/Bridge as a function of how much of the
observation is kept. The gain grows as less is discarded and peaks where
nothing is, while model time per call barely moves.}
\label{tab:keep}
\setlength{\tabcolsep}{6pt}
\begin{tabular}{r r r r}
\toprule
Keep (\%) & $\Delta$ success & $p$ & $\Delta$ model time \\
\midrule
__BODY__
\bottomrule
\end{tabular}
\end{table}
""".replace("__BODY__", "\n".join(body))
    open(os.path.join(OUT, "tablekeep.tex"), "w").write(tex)
    print("wrote tablekeep.tex")
    for keep, pat in rows:
        n, d, p = mcn(base, load(pat))
        print(f"  keep {keep:>3}% : Δ={d:+.1f}  p={p:.2g}")


# Result 1. Each row removes four layers; only the eligible window differs.
# (cell, baseline, wide/default window, narrow/deep window)
WINDOW = [
    ("OpenVLA/Fractal", "results/openvla_fractal_0806_baseline/**/results_*.json",
     "results/openvla_fractal_0806_depth_prune4/**/results_*.json",
     "results/openvla_fractal_depth_control/window875/**/results_*.json"),
    ("SpatialVLA/Fractal", "results/spatialvla_fractal_0806/baseline/**/results_*.json",
     "results/spatialvla_fractal_0806/depth_prune4/**/results_*.json",
     "results/spatialvla_depth_control/fractal/prune4_back/**/results_*.json"),
    ("SpatialVLA/Bridge", "results/spatialvla_bridge_0805/baseline/**/results_*.json",
     "results/spatialvla_bridge_0805/depth_prune4/**/results_*.json",
     "results/spatialvla_bridge_0805/depth_prune4_back/**/results_*.json"),
    ("OpenVLA/Bridge", "results/openvla_bridge_0805/baseline/**/results_*.json",
     "results/openvla_bridge_0805/depth_prune4/**/results_*.json",
     "results/openvla_bridge_depth_control/prune4_last/**/results_*.json"),
    ("UniVLA/Bridge", "results/univla_bridge_0805/baseline_l4/**/results_*.json",
     "results/univla_bridge_0805/depth_prune4/**/results_*.json",
     "results/univla_bridge_depth_control/prune4_last/**/results_*.json"),
]


def window_table():
    body = []
    for name, bp, wp, np_ in WINDOW:
        base = load(bp)
        _, dw, pw = mcn(base, load(wp))
        _, dn, pn = mcn(base, load(np_))
        body.append(f"{name} & {dfmt(dw)} & {pfmt(pw)} & {dfmt(dn)} & "
                    f"{pfmt(pn)} & ${abs(dw-dn):.1f}$ \\\\")
    tex = r"""%% Generated by make_ablation_tables.py. Result 1: depth pruning removes the
%% same four layers in every row; only the eligibility window changes -- a wide
%% window over the stack against one confined to the deepest layers. Paired
%% against each cell's own baseline, McNemar exact. Do not edit; regenerate.
\begin{table}[t]
\centering
\caption{Removing four layers under two eligibility windows. The change swings
from a gain to a large loss inside a single cell, and the size of that swing is
itself a property of the cell.}
\label{tab:window}
\setlength{\tabcolsep}{5pt}
\begin{tabular}{l rr rr r}
\toprule
& \multicolumn{2}{c}{Wide window} & \multicolumn{2}{c}{Deep window} & \\
\cmidrule(lr){2-3} \cmidrule(lr){4-5}
Cell & $\Delta$ & $p$ & $\Delta$ & $p$ & Span \\
\midrule
__BODY__
\bottomrule
\end{tabular}
\end{table}
""".replace("__BODY__", "\n".join(body))
    open(os.path.join(OUT, "tablewindow.tex"), "w").write(tex)
    print("wrote tablewindow.tex")
    for name, bp, wp, np_ in WINDOW:
        base = load(bp)
        _, dw, pw = mcn(base, load(wp))
        _, dn, pn = mcn(base, load(np_))
        print(f"  {name:18} wide {dw:+5.1f}  deep {dn:+6.1f}  span {abs(dw-dn):.1f}")


if __name__ == "__main__":
    keep_table()
    window_table()
