#!/usr/bin/env python3
"""Table I -- the grid, as a table instead of a heat map.

Built to be compared against fig_grid.pdf, not to replace it silently. The
measured reason it exists: RdBu_r is symmetric in lightness about zero, so in
greyscale +18.8 and -19.3 land at luminance 0.570 and 0.579, a difference of
0.009. A reviewer printing in black and white therefore cannot see the one
thing the figure is for. The numbers carry their own sign, so the figure
degrades to a table anyway; this makes that the design rather than the failure
mode.

Every number comes from build_grid_report.paired(), the same call the figure
and verify_all.py use, so the two cannot disagree.

Output: paper/tablegrid.tex
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_grid_report import discover, paired, grid_family  # noqa: E402
from make_grid_figure import ROWS, COLS, ALIASES, value  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "paper")

FAMILY_BREAK = {2, 4}  # row indices that start a new intervention family


def main():
    data = discover()
    cols = sorted({(b, k) for b, k, _ in COLS
                   if any(x[0] == b and x[1] == k for x in data)})
    fam = grid_family(data, cols)
    alpha = 0.05 / max(1, fam)

    body = []
    n_sig = 0
    for i, (cond, label) in enumerate(ROWS):
        if i in FAMILY_BREAK:
            body.append(r"\addlinespace[2pt]")
        cells = []
        for bb, bench, _ in COLS:
            got = value(data, bb, bench, cond)
            if got is None:
                cells.append(r"\textemdash")
                continue
            v, p = got
            # A number that is exactly zero carries no direction, so it gets no
            # sign. Everything else does, because the sign is the whole point.
            # Math mode, so the sign is a real minus rather than the hyphen
            # LaTeX sets in text mode. In a column of signed numbers a hyphen
            # is both too short and sits at the wrong height.
            # \textbf around $...$ does nothing: math mode ignores the text
            # weight, so the "bold" cells would have rendered identical to the
            # rest and the significance column would have been silently blank.
            # \mathbf inside the maths is what actually sets the digits bold.
            body_ = "0.0" if v == 0 else "%+.1f" % v
            if p < alpha:
                n_sig += 1
                s = r"$\mathbf{%s}$" % body_
            else:
                s = "$%s$" % body_
            cells.append(s)
        body.append(f"{label} & " + " & ".join(cells) + r" \\")

    head = (r"\multicolumn{3}{c}{WidowX-Bridge} & "
            r"\multicolumn{3}{c}{Google Robot/Fractal}")
    # The backbone names are set as the papers write them. \textsc lower-cased
    # them into small capitals, so OpenVLA came out OPENVLA and SpatialVLA
    # SPATIALVLA, which is neither the model's name nor anything the text uses.
    sub = " & ".join(b for b, _, _ in COLS)

    tex = r"""%% ---------------------------------------------------------------------------
%% Table I -- the grid. Generated by experiments/make_grid_table.py; do not
%% edit the numbers here, because there are none to edit. Regenerate instead.
%%
%% Spans both columns, so table* and not table. Needs \usepackage{booktabs}.
%%
%% The caption is ONE sentence on purpose. IEEEtran sets table captions in
%% small capitals, which is fine for a line and unreadable for six, and the
%% first draft ran to six. Everything a reader needs but does not need in
%% capitals sits in a \footnotesize note under the rule instead, which is the
%% usual IEEE arrangement. Do not grow the caption; grow the note.
%% ---------------------------------------------------------------------------
\begin{table*}[t]
\centering
\caption{Paired change in success points against each cell's own baseline.}
\label{tab:grid}
\setlength{\tabcolsep}{5pt}
\begin{tabular}{l rrr rrr}
\toprule
& \multicolumn{3}{c}{WidowX-Bridge} & \multicolumn{3}{c}{Google Robot/Fractal} \\
\cmidrule(lr){2-4} \cmidrule(lr){5-7}
\multicolumn{1}{c}{condition} & %s \\
\midrule
%s
\bottomrule
\end{tabular}

\vspace{3pt}
\parbox{\textwidth}{\footnotesize A cell pairs only the episodes present in
both runs. \textbf{Bold} marks the %d cells that clear a Bonferroni threshold
of $\alpha = 0.05/%d$ over the paired tests the grid runs, and \textemdash{}
marks the cell whose checkpoint is not public. Read along any row. The same
intervention, applied the same way, moves in both directions depending only on
which cell it was measured in, and the last row does so with both directions
individually significant.}
\end{table*}
""" % (sub, "\n".join(body), n_sig, fam)

    path = os.path.join(OUT, "tablegrid.tex")
    with open(path, "w") as fh:
        fh.write(tex)
    print(f"{n_sig} cells clear the correction, family of {fam}")
    print("wrote", path)


if __name__ == "__main__":
    main()
