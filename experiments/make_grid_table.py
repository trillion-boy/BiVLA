#!/usr/bin/env python3
"""Table I -- the grid, as a table instead of a heat map.

Built to be compared against fig_grid.pdf, not to replace it silently. The
measured reason it exists: RdBu_r is symmetric in lightness about zero, so in
greyscale +18.8 and -19.3 land at luminance 0.570 and 0.579, a difference of
0.009. A reviewer printing in black and white therefore cannot see the one
thing the figure is for. The numbers carry their own sign, so the figure
degrades to a table anyway; this makes that the design rather than the failure
mode.

Every number comes from build_grid_report.paired(), the same call the figure
and verify_all.py use, so the two cannot disagree.

Output: paper/tablegrid.tex
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_grid_report import discover, paired, grid_family  # noqa: E402
from make_grid_figure import ROWS, COLS, ALIASES, value  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "paper")

FAMILY_BREAK = {2, 4}  # row indices that start a new intervention family


def main():
    data = discover()
    cols = sorted({(b, k) for b, k, _ in COLS
                   if any(x[0] == b and x[1] == k for x in data)})
    fam = grid_family(data, cols)
    alpha = 0.05 / max(1, fam)

    # The baseline row. A -10 point drop from 90% and one from 15% are not the
    # same result, and without the absolute rate a reader cannot tell which
    # they are looking at. Computed from the same records, not transcribed.
    base_cells = []
    for bb, bench, _ in COLS:
        base = data.get((bb, bench, "baseline"))
        if not base:
            base_cells.append(r"\textemdash")
            continue
        n = sum(len(e) for e in base.values())
        ok = sum(sum(1 for v in e.values() if v) for e in base.values())
        base_cells.append("$%.1f$" % (100.0 * ok / n))
    base_row = "Baseline success (\\%) & " + " & ".join(base_cells) + r" \\"

    body = []
    n_sig = 0
    for i, (cond, label) in enumerate(ROWS):
        if i in FAMILY_BREAK:
            body.append(r"\addlinespace[2pt]")
        cells = []
        for bb, bench, _ in COLS:
            got = value(data, bb, bench, cond)
            if got is None:
                cells.append(r"\textemdash")
                continue
            v, p = got
            # A number that is exactly zero carries no direction, so it gets no
            # sign. Everything else does, because the sign is the whole point.
            # Math mode, so the sign is a real minus rather than the hyphen
            # LaTeX sets in text mode. In a column of signed numbers a hyphen
            # is both too short and sits at the wrong height.
            # \textbf around $...$ does nothing: math mode ignores the text
            # weight, so the "bold" cells would have rendered identical to the
            # rest and the significance column would have been silently blank.
            # \mathbf inside the maths is what actually sets the digits bold.
            # \\phantom{+} so an unsigned zero occupies the same width as a
            # signed number. The column is right-aligned and every value has one
            # decimal, so decimals line up on their own -- except for the zeros,
            # which were a character narrower and hung to the right of the rest.
            body_ = r"\phantom{+}0.0" if v == 0 else "%+.1f" % v
            if p < alpha:
                n_sig += 1
                s = r"$\mathbf{%s}$" % body_
            else:
                s = "$%s$" % body_
            cells.append(s)
        body.append(f"{label[0].upper() + label[1:]} & "
                    + " & ".join(cells) + r" \\")

    head = (r"\multicolumn{3}{c}{WidowX-Bridge} & "
            r"\multicolumn{3}{c}{Google Robot/Fractal}")
    # The backbone names are set as the papers write them. \textsc lower-cased
    # them into small capitals, so OpenVLA came out OPENVLA and SpatialVLA
    # SPATIALVLA, which is neither the model's name nor anything the text uses.
    sub = " & ".join(b for b, _, _ in COLS)

    tex = r"""%% ---------------------------------------------------------------------------
%% Table I -- the grid. Generated by experiments/make_grid_table.py; do not
%% edit the numbers here, because there are none to edit. Regenerate instead.
%%
%% Spans both columns, so table* and not table. Needs \usepackage{booktabs}.
%%
%% The caption is ONE sentence and the note is a KEY, not an argument. ieeeconf
%% sets table captions in small capitals, which is unreadable past a line, and
%% the first draft ran to six. The note under the rule used to end with "Read
%% along any row. The same intervention ... moves in both directions", which is
%% the Introduction's own result 3 restated. A caption says what a table shows,
%% the body says what it means, and the body already does. Do not grow either
%% one back.
%%
%% The caption covers BOTH kinds of number. It used to read "paired change ...
%% against each cell's own baseline", which stopped describing the table the
%% moment the baseline row went in, since the first row is an absolute rate and
%% not a change. It also names the unit once, as percentage points, so the
%% prose can go on saying "points" without either being loose.
%%
%% The caption covers BOTH kinds of number. It used to say "paired change ...
%% against each cell's own baseline", which stopped describing the table the
%% moment the baseline row went in: the first row is an absolute rate, not a
%% change. It also names the unit once, as percentage points, so the prose can
%% keep saying "points" without either being loose.
%% ---------------------------------------------------------------------------
\begin{table*}[t]
\centering
\caption{Baseline success rates and paired changes, in percentage points.}
\label{tab:grid}
\setlength{\tabcolsep}{5pt}
\begin{tabular}{l rrr rrr}
\toprule
& \multicolumn{3}{c}{WidowX-Bridge} & \multicolumn{3}{c}{Google Robot/Fractal} \\
\cmidrule(lr){2-4} \cmidrule(lr){5-7}
\multicolumn{1}{c}{Condition} & %s \\
\midrule
%s
\midrule
%s
\bottomrule
\end{tabular}

\vspace{3pt}
\parbox{\textwidth}{\footnotesize The first row is each cell's absolute
baseline success rate. Every row below it is the paired change against that
rate, over the episodes present in both runs. \textbf{Bold} marks
the %d cells that clear a Bonferroni threshold of $\alpha = 0.05/%d$ over the
paired tests the grid runs. \textemdash{} marks the cell whose checkpoint is
not public.}
\end{table*}
""" % (sub, base_row, "\n".join(body), n_sig, fam)

    path = os.path.join(OUT, "tablegrid.tex")
    with open(path, "w") as fh:
        fh.write(tex)
    print(f"{n_sig} cells clear the correction, family of {fam}")
    print("wrote", path)


if __name__ == "__main__":
    main()
